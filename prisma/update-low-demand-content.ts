function validateContent() {
  const articleSlugs = new Set(articles.map((item) => item.slug));
  const guideSlugs = new Set(guides.map((item) => item.slug));
  if (articleSlugs.size !== articles.length || guideSlugs.size !== guides.length) {
    throw new Error("Duplicate content slug in update payload");
  }

  for (const article of articles) {
    if (!article.body.includes("<h2>") || !article.body.includes("<p>")) {
      throw new Error(`Article ${article.slug} does not contain semantic markup`);
    }
  }

  const combined = JSON.stringify({ articles, guides });
  const forbidden = [/50-60% модели/i, /студия забирает 35/i, /модел[ьи] получает 60/i];
  for (const pattern of forbidden) {
    if (pattern.test(combined)) throw new Error(`Forbidden percentage claim: ${pattern}`);
  }
}

function sameValue(current: unknown, next: unknown) {
  return JSON.stringify(current) === JSON.stringify(next);
}

async function main() {
  validateContent();
  if (process.argv.includes("--validate-only")) {
    console.log(`${VERSION}: payload valid (${articles.length} articles, ${guides.length} guides)`);
    return;
  }

  const apply = process.argv.includes("--apply");
  if (apply && process.env.CONTENT_UPDATE_CONFIRM !== VERSION) {
    throw new Error(`Set CONTENT_UPDATE_CONFIRM=${VERSION} before applying`);
  }

  const currentArticles = await prisma.article.findMany({
    where: { slug: { in: articles.map((item) => item.slug) } }
  });
  const currentGuides = await prisma.guide.findMany({
    where: { slug: { in: guides.map((item) => item.slug) } }
  });

  const missingArticles = articles.filter((item) => !currentArticles.some((row) => row.slug === item.slug));
  const missingGuides = guides.filter((item) => !currentGuides.some((row) => row.slug === item.slug));
  if (missingArticles.length || missingGuides.length) {
    throw new Error(`Missing targets: articles=${missingArticles.map((item) => item.slug).join(",") || "none"}; guides=${missingGuides.map((item) => item.slug).join(",") || "none"}`);
  }

  const changedArticles = articles.filter((next) => {
    const current = currentArticles.find((item) => item.slug === next.slug)!;
    return !sameValue({ title: current.title, summary: current.summary, body: current.body }, { title: next.title, summary: next.summary, body: next.body });
  });
  const changedGuides = guides.filter((next) => {
    const current = currentGuides.find((item) => item.slug === next.slug)!;
    const currentValue = {
      title: current.title, h1: current.h1, description: current.description, intro: current.intro,
      category: current.category, audience: current.audience, authorName: current.authorName,
      authorTitle: current.authorTitle, quickAnswer: current.quickAnswer, keywords: current.keywords,
      sections: current.sections, checklist: current.checklist, mistakes: current.mistakes,
      faq: current.faq, ctaLabel: current.ctaLabel, ctaHref: current.ctaHref, related: current.related
    };
    const nextValue = {
      title: next.title, h1: next.h1, description: next.description, intro: next.intro,
      category: next.category, audience: next.audience, authorName: next.authorName,
      authorTitle: next.authorTitle, quickAnswer: next.quickAnswer, keywords: next.keywords,
      sections: JSON.stringify(next.sections), checklist: JSON.stringify(next.checklist), mistakes: JSON.stringify(next.mistakes),
      faq: JSON.stringify(next.faq), ctaLabel: next.ctaLabel, ctaHref: next.ctaHref, related: next.related
    };
    return !sameValue(currentValue, nextValue);
  });

  console.log(`${VERSION}: ${changedArticles.length} article(s), ${changedGuides.length} guide(s) need updates`);
  if (!apply || (!changedArticles.length && !changedGuides.length)) return;

  const backupDir = process.env.CONTENT_BACKUP_DIR || "/tmp/mycamdesk-content-backups";
  await mkdir(backupDir, { recursive: true });
  const timestamp = new Date().toISOString().replaceAll(":", "-");
  const backupPath = path.join(backupDir, `${VERSION}-${timestamp}.json`);
  await writeFile(backupPath, JSON.stringify({ version: VERSION, createdAt: new Date().toISOString(), articles: currentArticles, guides: currentGuides }, null, 2));

  await prisma.$transaction([
    ...changedArticles.map((item) => prisma.article.update({
      where: { slug: item.slug },
      data: { title: item.title, summary: item.summary, body: item.body }
    })),
    ...changedGuides.map((item) => prisma.guide.update({
      where: { slug: item.slug },
      data: {
        title: item.title, h1: item.h1, description: item.description, intro: item.intro,
        category: item.category, audience: item.audience, authorName: item.authorName,
        authorTitle: item.authorTitle, quickAnswer: item.quickAnswer, keywords: item.keywords,
        sections: JSON.stringify(item.sections), checklist: JSON.stringify(item.checklist),
        mistakes: JSON.stringify(item.mistakes), faq: JSON.stringify(item.faq),
        ctaLabel: item.ctaLabel, ctaHref: item.ctaHref, related: item.related
      }
    }))
  ]);

  console.log(`${VERSION}: update complete; backup=${backupPath}`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
